"""Generated blocks inside authored documents.

A block is the text between `<!-- vbench:begin NAME -->` and `<!-- vbench:end NAME -->`. `vbench sync` rewrites
only what is inside known blocks; everything around them is the author's. `check docs` compares each block with
a fresh render, so a derived view (build order, requirement coverage) cannot drift from the specs it comes from.

    backlog doc       dependencies  use case | depends on | enables
                      waves         the build order as a table and a Mermaid graph
                      coverage      requirement | realised by
    requirements doc  fr-map        use case | realises | spec link
"""

from __future__ import annotations

import posixpath
import re

from ..ports import Workspace
from .config import Config
from .graph import enables, read_links, to_mermaid, waves
from .ids import FR_ID, REQ_ID
from .model import natural_key
from .specs import SpecInfo, read_specs, row

BLOCK = re.compile(
    r"(?P<head><!-- vbench:begin (?P<name>[\w-]+) -->\n)(?P<body>.*?)(?P<tail><!-- vbench:end (?P=name) -->)", re.DOTALL
)
FR_ROW = re.compile(rf"^\|\s*\*\*({FR_ID})\*\*\s*\|([^|]*)\|", re.MULTILINE)
EMPTY = "_Generated by `vbench sync` from the use-case specs. There are none yet._\n"
BLOCKS = {"backlog": ("dependencies", "waves", "coverage"), "requirements": ("fr-map",), "registry": ("registry",)}


def _label(s: SpecInfo) -> str:
    return f"**{s.uc}** {s.title}"


def requirements_declared(cfg: Config, ws: Workspace) -> list[str]:
    """FR ids in the requirements doc, skipping the template's `(placeholder)` rows."""
    if not ws.exists(cfg.requirements):
        return []
    return sorted(
        {m.group(1) for m in FR_ROW.finditer(ws.read(cfg.requirements)) if not m.group(2).strip().startswith("(")},
        key=natural_key,
    )


def _realises(cfg: Config, ws: Workspace) -> dict[str, list[str]]:
    out = {}
    for s in read_specs(cfg, ws):
        out[s.uc] = sorted(set(REQ_ID.findall(row(ws.read(s.path), "Realises") or "")), key=natural_key)
    return out


def render_block(name: str, cfg: Config, ws: Workspace, doc: str) -> str:
    if name == "registry":  # appended to, never rewritten; imported here because the registry reads the whole V view
        from .registry import render_registry

        return render_registry(cfg, ws, doc)
    specs = sorted(read_specs(cfg, ws), key=lambda s: natural_key(s.uc))
    if not specs:
        return EMPTY
    deps = read_links(cfg, ws)
    if name == "dependencies":
        back = enables(deps)
        lines = ["| Use case | Depends on | Enables |", "|---|---|---|"]
        lines += [
            f"| {_label(s)} | {', '.join(deps[s.uc]) or '-'} | "
            f"{', '.join(sorted(back[s.uc], key=natural_key)) or '-'} |"
            for s in specs
        ]
        return "\n".join(lines) + "\n"
    if name == "waves":
        wave = waves(deps)
        lines = ["| Wave | Use cases |", "|---|---|"]
        for w in sorted(set(wave.values())):
            lines.append(f"| **{w}** | {', '.join(sorted((u for u in wave if wave[u] == w), key=natural_key))} |")
        return "\n".join(lines) + "\n\n```mermaid\n" + to_mermaid(deps) + "\n```\n"
    realises = _realises(cfg, ws)
    if name == "fr-map":
        lines = ["| Use case | Realises | Spec |", "|---|---|---|"]
        for s in specs:
            link = posixpath.relpath(s.path, posixpath.dirname(doc) or ".")
            lines.append(
                f"| {_label(s)} | {', '.join(realises[s.uc]) or '-'} | [{posixpath.basename(s.path)}]({link}) |"
            )
        return "\n".join(lines) + "\n"
    if name == "coverage":
        declared = requirements_declared(cfg, ws)
        by_req: dict[str, list[str]] = {}
        for uc, reqs in realises.items():
            for r in reqs:
                by_req.setdefault(r, []).append(uc)
        lines = ["| Requirement | Realised by |", "|---|---|"]
        lines += [f"| {r} | {', '.join(sorted(by_req.get(r, []), key=natural_key)) or '**none**'} |" for r in declared]
        unknown = sorted((r for r in by_req if r.startswith("REQ-FR-") and r not in declared), key=natural_key)
        if unknown:
            lines.append("")
            lines.append("Named by a use case but not in the requirements doc: " + ", ".join(unknown) + ".")
        if len(lines) == 2:
            return "_No functional requirements are recorded in the requirements doc yet._\n"
        return "\n".join(lines) + "\n"
    raise KeyError(name)


def docs_with_blocks(cfg: Config, ws: Workspace) -> list[tuple[str, tuple[str, ...]]]:
    return [
        (p, names)
        for p, names in (
            (cfg.backlog, BLOCKS["backlog"]),
            (cfg.requirements, BLOCKS["requirements"]),
            (f"{cfg.docs.rstrip('/')}/00-id-registry.md", BLOCKS["registry"]),
        )
        if ws.exists(p)
    ]


def regenerate(text: str, names: tuple[str, ...], cfg: Config, ws: Workspace, doc: str) -> str:
    def swap(m: re.Match[str]) -> str:
        if m.group("name") not in names:
            return m.group(0)
        return m.group("head") + render_block(m.group("name"), cfg, ws, doc) + m.group("tail")

    return BLOCK.sub(swap, text)


def stale_blocks(cfg: Config, ws: Workspace) -> list[tuple[str, str]]:
    """[(doc, block name)] whose text differs from a fresh render."""
    out = []
    for doc, names in docs_with_blocks(cfg, ws):
        text = ws.read(doc)
        for m in BLOCK.finditer(text):
            if m.group("name") in names and m.group("body") != render_block(m.group("name"), cfg, ws, doc):
                out.append((doc, m.group("name")))
    return out
