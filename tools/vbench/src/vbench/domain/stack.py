"""The opinionated stack (`python-fastapi`) as pure rules: naming, and the architecture contract derived from the code.

Ports and adapters with DDD means one package per bounded context with `domain`, `application` and `adapters`. The
rules that keep it that way are an import-linter contract, generated here from the contexts that exist so that it can
never lag behind the code. `uv run lint-imports` (the `boundaries` gate) is what fails when a rule is broken.
"""

from __future__ import annotations

import posixpath
import re

from ..ports import Workspace
from .config import Config

STACKS = ("python-fastapi", "none")
SHARED = {"shared_kernel", "infrastructure"}  # packages under the root that are not bounded contexts
FRAMEWORKS = ("fastapi", "sqlalchemy", "psycopg", "httpx", "pydantic_settings")
LAYERS = {  # package -> the docstring it starts with
    "": "{name}: a bounded context. Reach it from another context only through its `public` module.",
    "domain": "{name} domain: aggregates, value objects, domain events. Imports no framework.",
    "application": "{name} application: use cases, and the ports they need. Imports no framework.",
    "application/ports": "Ports: the interfaces the use cases need from the outside world (repositories, gateways).",
    "application/use_cases": "Use cases: one module per behaviour a context offers.",
    "adapters": "{name} adapters: the technology around the core.",
    "adapters/inbound": "Driving adapters: FastAPI routers and consumers that call the use cases.",
    "adapters/outbound": "Driven adapters: SQLAlchemy repositories and clients that implement the ports.",
}


def package_name(name: str) -> str:
    """`My Notes App` -> `my_notes_app`; always a valid Python identifier."""
    ident = re.sub(r"[^a-z0-9]+", "_", name.lower()).strip("_")
    if not ident:
        return "app"
    return f"app_{ident}" if ident[0].isdigit() else ident


def dist_name(name: str) -> str:
    """`My Notes App` -> `my-notes-app`; a valid distribution name for pyproject.toml and Docker."""
    return re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-") or "app"


def display_name(name: str) -> str:
    """The name as shown to people, made safe to sit inside a quoted string in TOML and Python."""
    return re.sub(r'["\\\r\n]', "", name).strip() or "app"


def context_package(slug: str) -> str:
    """`tagging-search` -> `tagging_search`."""
    return package_name(slug.replace("-", "_"))


def code_contexts(cfg: Config, ws: Workspace) -> list[str]:
    """The bounded contexts that exist in the code: a package under the root with a `domain` package inside."""
    if not cfg.stack or not cfg.package or not cfg.prod:
        return []
    root = f"{cfg.prod[0].rstrip('/')}/{cfg.package}"
    found: set[str] = set()
    for path in ws.files([root], [".py"]):
        parts = posixpath.relpath(path, root).split("/")  # e.g. ["notes", "domain", "__init__.py"]
        if len(parts) == 3 and parts[1] == "domain" and parts[2] == "__init__.py":
            found.add(parts[0])
    return sorted(c for c in found if c not in SHARED)


def importlinter_text(package: str, contexts: list[str]) -> str:
    """The `.importlinter` file for a root package and its contexts. Rewritten whenever a context is added."""
    out = [
        f"# Generated by vbench from the bounded contexts under src/{package}. `vbench new context` rewrites it.",
        "# This is the ports-and-adapters rule as a failing check: `uv run lint-imports` (the `boundaries` gate).",
        "[importlinter]",
        f"root_package = {package}",
        "include_external_packages = True",
        "",
        "[importlinter:contract:top-level]",
        "name = main > infrastructure > shared_kernel",
        "type = layers",
        "layers =",
        f"    {package}.main",
        f"    {package}.infrastructure",
        f"    {package}.shared_kernel",
    ]
    for c in contexts:
        out += [
            "",
            f"[importlinter:contract:{c}-layers]",
            f"name = {c}: adapters > application > domain",
            "type = layers",
            "layers =",
            f"    {package}.{c}.adapters",
            f"    {package}.{c}.application",
            f"    {package}.{c}.domain",
        ]
    if contexts:
        out += [
            "",
            "[importlinter:contract:pure-core]",
            "name = domain and application import no framework",
            "type = forbidden",
            "source_modules =",
        ]
        out += [f"    {package}.{c}.{layer}" for c in contexts for layer in ("domain", "application")]
        out += ["forbidden_modules ="] + [f"    {m}" for m in FRAMEWORKS]
    if len(contexts) > 1:
        out += [
            "",
            "[importlinter:contract:contexts]",
            "name = contexts are independent, except through a public module",
            "type = independence",
            "modules =",
        ]
        out += [f"    {package}.{c}" for c in contexts]
        out += ["ignore_imports ="] + [f"    {package}.** -> {package}.{c}.public" for c in contexts]
        out += ["unmatched_ignore_imports_alerting = none"]
    return "\n".join(out) + "\n"
