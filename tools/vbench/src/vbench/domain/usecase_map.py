"""The overall use-case diagram, generated from the specs.

Only structure goes in (actor, bounded context, title, dependencies), never progress, so the file changes when a
spec header changes and not on every commit. A check compares it with a fresh render, so it cannot go stale.
"""

from __future__ import annotations

import re

from ..ports import Workspace
from .config import Config
from .graph import read_links
from .model import natural_key
from .specs import SpecInfo, read_specs

HEADER = "' GENERATED by `vbench sync` from the use-case specs. Do not edit: change a spec header and re-run."
ACTOR_COLOURS = ["#1565C0", "#6A1B9A", "#AD1457", "#E65100", "#00695C", "#455A64"]
BOX_COLOURS = ["#E8F0FE", "#EDE7F6", "#E0F2F1", "#FFF3E0", "#E0F7FA", "#F3E5F5"]
UNASSIGNED = "Unassigned"


def _alias(prefix: str, text: str) -> str:
    return prefix + re.sub(r"[^A-Za-z0-9]+", "_", text).strip("_")


def render_usecase_map(cfg: Config, ws: Workspace) -> str:
    specs = sorted(read_specs(cfg, ws), key=lambda s: natural_key(s.uc))
    deps = read_links(cfg, ws)
    actors = sorted({s.actor for s in specs if s.actor})
    contexts = sorted({s.context or UNASSIGNED for s in specs}, key=lambda c: (c == UNASSIGNED, c.lower()))

    lines = [
        HEADER,
        "@startuml UseCases",
        "!include _style.puml",
        "title Use Case View",
        "",
        "top to bottom direction",
        "skinparam actorStyle awesome",
        "skinparam linetype ortho",
        "",
    ]
    for i, a in enumerate(actors):
        lines.append(f'actor "{a}" as {_alias("ACT_", a)} {ACTOR_COLOURS[i % len(ACTOR_COLOURS)]}')
    lines.append("")
    by_context: dict[str, list[SpecInfo]] = {c: [] for c in contexts}
    for s in specs:
        by_context[s.context or UNASSIGNED].append(s)
    lines.append('rectangle "System" {')
    for i, c in enumerate(contexts):
        lines.append(f'  rectangle "{c}" as {_alias("CTX_", c)} {BOX_COLOURS[i % len(BOX_COLOURS)]} {{')
        for s in by_context[c]:
            lines.append(f'    usecase "{s.uc}\\n{s.title}" as {_alias("", s.uc)}')
        lines.append("  }")
    lines += ["}", ""]
    for s in specs:
        if s.actor:
            lines.append(f"{_alias('ACT_', s.actor)} --> {_alias('', s.uc)}")
    for s in specs:
        for d in deps.get(s.uc, []):
            if d in deps:
                lines.append(f"{_alias('', s.uc)} ..> {_alias('', d)} : needs")
    lines += ["@enduml", ""]
    return "\n".join(lines)
